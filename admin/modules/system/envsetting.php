<?php
/**
 * This file is generated by the System Environment Settings page.
 * Do not edit it through untrusted input.
 */
\$env = {$environment};
\$conditional_environment = {$conditionalEnvironment};
\$based_on_ip = {$basedOnIp};
\$range_ip = {$rangeIp};

if (\$based_on_ip) {
    // Only use the peer address. HTTP_X_FORWARDED_FOR is client-controlled
    // unless the deployment has an explicit trusted-proxy policy.
    if (in_array(\$_SERVER['REMOTE_ADDR'] ?? '', \$range_ip, true)) {
        \$env = \$conditional_environment;
    }
}

if (php_sapi_name() === 'cli') {
    \$env = \$conditional_environment !== \$env ? \$conditional_environment : \$env;
}
PHP;
}

function envsettingWriteFile($file, $contents)
{
    $directory = dirname($file);
    if (!is_dir($directory) || !is_writable($directory) || is_link($file)) {
        return false;
    }

    $temporaryFile = tempnam($directory, '.env-');
    if ($temporaryFile === false) {
        return false;
    }

    $written = file_put_contents($temporaryFile, $contents, LOCK_EX);
    if ($written === false || $written !== strlen($contents)) {
        @unlink($temporaryFile);
        return false;
    }

    @chmod($temporaryFile, 0640);
    if (!@rename($temporaryFile, $file)) {
        @unlink($temporaryFile);
        return false;
    }

    if (function_exists('opcache_invalidate')) {
        @opcache_invalidate($file, true);
    }

    return true;
}

