function envsettingCurrentIp()
{
    return isset($_SERVER['REMOTE_ADDR']) ? $_SERVER['REMOTE_ADDR'] : '';
}

function envsettingEnvironment($value)
{
    return $value === 'production' ? 'production' : 'development';
}

function envsettingStoredDefaultEnvironment($file, $fallback)
{
    if (!$file || !is_file($file) || is_link($file) || !is_readable($file)) {
        return $fallback;
    }

    $contents = file_get_contents($file);
    if (!is_string($contents)) {
        return $fallback;
    }

    if (preg_match('/^\\s*\\$env\\s*=\\s*[\'\\"](production|development)[\'\\"]\\s*;/m', $contents, $matches)) {
        return $matches[1];
    }

    return $fallback;
}

function envsettingIpRange($value)
{
    if (!is_string($value) || trim($value) === '') {
        return array();
    }

    $range = array();
    foreach (explode(';', $value) as $ip) {
        $ip = trim($ip);
        if ($ip === '') {
            continue;
        }

        if (filter_var($ip, FILTER_VALIDATE_IP) === false) {
            return false;
        }

        $range[$ip] = $ip;
    }

    return array_values($range);
}

function envsettingFileContents($environment, $conditionalEnvironment, $basedOnIp, array $rangeIp)
{
    $environment = var_export($environment, true);
    $conditionalEnvironment = var_export($conditionalEnvironment, true);
    $basedOnIp = $basedOnIp ? 'true' : 'false';
    $rangeIp = var_export($rangeIp, true);

